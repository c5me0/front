function photoSheet(p) {
  const g = sub(p, 'grid', grid);
  const liveCell = sub(p, 'liveCell', (l) => ({
    nodeId: field(l, 'nodeId', 'string'),
    image: field(l, 'image', 'image'),
    row: field(l, 'row', 'int'),
    col: field(l, 'col', 'int'),
    rowSpan: field(l, 'rowSpan', 'int'),
  }));
  const covered = new Set();
  for (let dr = 0; dr < liveCell.rowSpan; dr++) {
    const r = liveCell.row - 1 + dr;
    if (g.rows[r]?.[liveCell.col - 1] === undefined) fail(`${at()}.liveCell: 그리드 밖 칸 r${r + 1}c${liveCell.col} 을 덮음`);
    covered.add(`${r}:${liveCell.col - 1}`);
  }
  const selected = each(p, 'selected', (s) => {
    const row = field(s, 'row', 'int');
    const col = field(s, 'col', 'int');
    if (g.rows[row - 1]?.[col - 1] === undefined) fail(`${at()}: 그리드 밖 칸 r${row}c${col}`);
    if (covered.has(`${row - 1}:${col - 1}`)) fail(`${at()}: 실시간 칸이 덮은 칸 r${row}c${col} 은 선택할 수 없다`);
    return `${row - 1}:${col - 1}`;
  });
  const photos = [];
  g.rows.forEach((row, r) =>
    row.forEach((image, c) => {
      if (!covered.has(`${r}:${c}`)) photos.push({ image, selected: selected.includes(`${r}:${c}`) });
    }),
  );
  return {
    screenNodeId: field(p, 'screenNodeId', 'string'),
    nodeId: field(p, 'nodeId', 'string'),
    title: field(p, 'title', 'string'),
    liveCell,
    columns: g.columns,
    rows: g.rows,
    photos,
  };
}

function albumV5Section(s) {
  const kind = field(s, 'kind', SECTION_KINDS);
  const tint = member(s, 'tint', COLOR_ROLES, '색 역할');
  where.push('heroGradient');
  if (!('heroGradient' in s)) fail(`lab-content.json: ${at()} 없음`);
  where.pop();
  const heroGradient = s.heroGradient === null ? null : member(s, 'heroGradient', GRADIENT_NAMES, '그라데이션');
  const cover = field(s, 'cover', 'image?');
  const callCards = each(s, 'callCards', (c) => {
    const direction = field(c, 'direction', DIRECTIONS);
    const icon = field(c, 'icon', ['arrow-up-right', 'arrow-down-left']);
    if (icon !== ICON_OF_DIRECTION[direction]) fail(`${at()}.icon: ${direction} 카드 아이콘은 ${ICON_OF_DIRECTION[direction]} (E4 — 방향 데이터로)`);
    const variant = field(c, 'variant', CARD_VARIANTS);
    if ((variant === 'failed') !== (direction === 'missed')) fail(`${at()}.variant: 부재중(missed) ⇔ failed`);
    return {
      nodeId: field(c, 'nodeId', 'string'),
      variant,
      direction,
      icon,
      title: field(c, 'title', 'string'),
      subtitle: each(c, 'subtitle', (sp) => ({ text: field(sp, 'text', 'string'), weight: field(sp, 'weight', WEIGHTS) })),
    };
  });
  const featured = each(s, 'featured', featuredTile);
  const g = sub(s, 'grid', grid, true);
  const hasHero = cover !== null && heroGradient !== null;
  if ((cover === null) !== (heroGradient === null)) fail(`${at()}: cover 와 heroGradient 는 함께 있거나 함께 null`);
  if (kind === 'callsOnly' && (hasHero || g !== null || callCards.length === 0))
    fail(`${at()}: callsOnly = 히어로 · 그리드 없음 + 카드 1장 이상 (Figma 2232:2165)`);
  if (kind === 'photosOnly' && (!hasHero || g === null || callCards.length > 0)) fail(`${at()}: photosOnly = 히어로 + 그리드, 카드 없음`);
  if (kind === 'photosCalls' && (!hasHero || g === null || callCards.length === 0)) fail(`${at()}: photosCalls = 히어로 + 카드 + 그리드`);
  if (featured.length && g === null) fail(`${at()}.featured: 그리드 없는 섹션`);
  return {
    id: field(s, 'id', 'string'),
    figmaName: field(s, 'figmaName', 'string'),
    nodeId: field(s, 'nodeId', 'string'),
    kind,
    tint,
    heroGradient,
    cover,
    title: field(s, 'title', 'string'),
    subtitle: field(s, 'subtitle', 'string'),
    stats: sub(s, 'stats', (st) => ({ photos: field(st, 'photos', 'string'), calls: field(st, 'calls', 'string') })),
    callCards,
    grid: g === null ? null : withPhotos(g, featured),
    featured,
  };
}

