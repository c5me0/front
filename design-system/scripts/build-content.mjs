const at = () => where.join('.');
function field(obj, key, kind) {
  where.push(key);
  if (!(key in obj)) fail(`lab-content.json: ${at()} 없음`);
  const v = obj[key];
  check(v, kind);
  where.pop();
  return v;
}
function check(v, kind) {
  if (kind === 'string' && typeof v !== 'string') fail(`${at()}: string 이어야 함`);
  if (kind === 'number' && typeof v !== 'number') fail(`${at()}: number 이어야 함`);
  if (kind === 'int' && !Number.isInteger(v)) fail(`${at()}: 정수여야 함`);
  if (kind === 'bool' && typeof v !== 'boolean') fail(`${at()}: boolean 이어야 함`);
  if (kind === 'array' && !Array.isArray(v)) fail(`${at()}: array 여야 함`);
  if (kind === 'object' && (typeof v !== 'object' || v === null || Array.isArray(v))) fail(`${at()}: object 여야 함`);
  if (kind === 'image' && !imageByFile.has(v)) fail(`${at()}: manifest 에 없는 이미지 '${v}'`);
  if (kind === 'image?' && v !== null && !imageByFile.has(v)) fail(`${at()}: manifest 에 없는 이미지 '${v}'`);
  if (Array.isArray(kind) && !kind.includes(v)) fail(`${at()}: ${kind.join(' | ')} 중 하나여야 함 (현재 ${JSON.stringify(v)})`);
}
function each(obj, key, fn) {
  const arr = field(obj, key, 'array');
  where.push(key);
  const out = arr.map((item, i) => {
    where.push(String(i));
    const r = fn(item);
    where.pop();
    return r;
  });
  where.pop();
  return out;
}
function sub(obj, key, fn, nullable = false) {
  where.push(key);
  if (!(key in obj)) fail(`lab-content.json: ${at()} 없음`);
  const v = obj[key];
  if (v === null && nullable) {
    where.pop();
    return null;
  }
  check(v, 'object');
  const r = fn(v);
  where.pop();
  return r;
}
const round6 = (n) => Math.round(n * 1e6) / 1e6;
function fraction(obj, key, px, total) {
  const v = field(obj, key, 'number');
  if (Math.abs(v - round6(px / total)) > 1e-6) fail(`${at()}.${key}: ${px}/${total} = ${round6(px / total)} 이어야 함 (현재 ${v})`);
  return v;
}

