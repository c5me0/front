function run(cmd, args) {
  return execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
}

function pixelSize(file) {
  const out = run('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', file]);
  const w = Number(/pixelWidth:\s*(\d+)/.exec(out)?.[1]);
  const h = Number(/pixelHeight:\s*(\d+)/.exec(out)?.[1]);
  if (!w || !h) throw new Error(`sips: 크기를 읽지 못함 ${file}`);
  return { width: w, height: h };
}

function assertNoMetadata(file) {
  const gps = run('exiftool', ['-s', '-s', '-s', '-gps:all', file]).trim();
  if (gps) throw new Error(`GPS 잔존: ${file}\n${gps}`);
  const groups = run('exiftool', ['-a', '-G0', '-s', file])
    .split('\n')
    .map((l) => /^\[([^\]]+)\]/.exec(l)?.[1])
    .filter(Boolean);
  const leftover = [...new Set(groups)].filter((g) => !ALLOWED_META_GROUPS.has(g));
  if (leftover.length) throw new Error(`메타데이터 잔존 (${leftover.join(', ')}): ${file}`);
}

function ingest() {
  for (const tool of ['sips', 'exiftool']) {
    try {
      execFileSync('which', [tool], { stdio: 'ignore' });
    } catch {
      fail(`--ingest 에는 ${tool} 이 필요합니다 (macOS sips, brew install exiftool)`);
    }
  }
  mkdirSync(IMAGES_DIR, { recursive: true });
  for (const f of ONLY) if (!imageByFile.has(f)) fail(`--only ${f}: manifest.json 에 없는 이미지`);
  const tmp = mkdtempSync(join(tmpdir(), 'cameo-content-'));
  try {
    for (const img of manifest.images) {
      if (ONLY.size && !ONLY.has(img.file)) continue;
      // Redacted mock slots must never be re-ingested from personal originals.
      if (img.source.kind === 'placeholder') continue;
      const src = resolve(root, img.source.path);
      if (!existsSync(src)) throw new Error(`원본 없음: ${img.source.path}`);

      const p = img.process;
      const ext = p.encode === 'png' ? 'png' : 'jpg';
      if (!img.file.endsWith(`.${ext}`)) throw new Error(`확장자와 encode 불일치: ${img.file} (${p.encode})`);

      const input = join(tmp, `in-${img.file}.${img.source.format === 'png' ? 'png' : 'jpg'}`);
      const output = join(tmp, img.file);
      copyFileSync(src, input);

      if (p.rotate != null && ![90, 180, 270].includes(p.rotate)) {
        throw new Error(`rotate 는 90 | 180 | 270 (시계 방향): ${img.file} (${p.rotate})`);
      }
      if (p.encode === 'copy') {
        if (img.source.format !== 'jpeg' || p.toSrgb || p.resizeToWidth || p.rotate) {
          throw new Error(`encode=copy 는 무변환 JPEG 에만 허용: ${img.file}`);
        }
        copyFileSync(input, output);
      } else {

        const args = [];
        if (p.toSrgb) args.push('--matchTo', SRGB_PROFILE);
        if (p.rotate) args.push('--rotate', String(p.rotate));
        if (p.resizeToWidth) args.push('--resampleWidth', String(p.resizeToWidth));
        if (p.encode === 'jpeg85') args.push('-s', 'format', 'jpeg', '-s', 'formatOptions', '85');
        else if (p.encode === 'png') args.push('-s', 'format', 'png');
        else throw new Error(`알 수 없는 encode: ${p.encode}`);
        run('sips', [...args, input, '--out', output]);
      }
      run('exiftool', ['-q', '-all=', '-overwrite_original', output]);
      assertNoMetadata(output);

      const buf = readFileSync(output);
      const size = pixelSize(output);
      if (p.resizeToWidth && size.width !== p.resizeToWidth) throw new Error(`축소 실패: ${img.file}`);
      img.output = {
        format: p.encode === 'png' ? 'png' : 'jpeg',
        width: size.width,
        height: size.height,
        bytes: buf.length,
        metadata: 'none (exiftool -all=; GPS verified absent)',
      };

      writeFileSync(join(IMAGES_DIR, img.file), buf);
      console.log(`ingested ${img.file} ${size.width}x${size.height} ${buf.length}B`);
    }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }

  for (const f of readdirSync(IMAGES_DIR)) {
    if (!imageByFile.has(f) || isAppleDouble(f)) rmSync(join(IMAGES_DIR, f), { force: true });
  }
  writeFileSync(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`wrote ${MANIFEST}`);
}

if (INGEST) {
  if (CHECK) fail('--ingest 와 --check 는 함께 쓸 수 없음');
  ingest();
}

