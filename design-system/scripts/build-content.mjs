let stale = false;
function sync(file, content) {
  const current = existsSync(file) ? readFileSync(file) : null;
  const same = current !== null && Buffer.compare(current, Buffer.isBuffer(content) ? content : Buffer.from(content)) === 0;
  if (CHECK) {
    if (!same) {
      console.error(`✗ stale: ${file}`);
      stale = true;
    }
    return;
  }
  if (!same) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    console.log(`wrote ${file}`);
  }
}

