const grid = (g) => {
  const columns = field(g, 'columns', 'int');
  const rows = each(g, 'rows', (row) => {
    check(row, 'array');
    if (row.length === 0 || row.length > columns) fail(`${at()}: 행의 칸 수는 1..${columns}`);
    row.forEach((f) => check(f, 'image'));
    return row;
  });
  return { columns, rows };
};

const LIKED_SPAN = 2;

function gridPhotos(g, featured = []) {
  const anchors = new Map();
  const covered = new Set();
  const cellAt = (r, c) => g.rows[r]?.[c];
  where.push('featured');
  featured.forEach((t, i) => {
    where.push(String(i));
    if (t.rowSpan !== LIKED_SPAN || t.colSpan !== LIKED_SPAN) fail(`${at()}: rowSpan·colSpan 은 ${LIKED_SPAN} 이어야 함 (2x2 = 좋아요)`);
    if (!t.liked) fail(`${at()}.liked: 2x2 추천 타일 = 좋아요한 사진 (interaction-spec §1) → true 여야 함`);
    const r0 = t.row - 1;
    const c0 = t.col - 1;
    for (let dr = 0; dr < LIKED_SPAN; dr++) {
      for (let dc = 0; dc < LIKED_SPAN; dc++) {
        const key = `${r0 + dr}:${c0 + dc}`;
        if (cellAt(r0 + dr, c0 + dc) === undefined) fail(`${at()}: 타일이 그리드 밖 칸 r${r0 + dr + 1}c${c0 + dc + 1} 을 덮음`);
        if (anchors.has(key) || covered.has(key)) fail(`${at()}: 다른 추천 타일과 겹침 (r${r0 + dr + 1}c${c0 + dc + 1})`);
        if (dr === 0 && dc === 0) anchors.set(key, t);
        else covered.add(key);
      }
    }
    where.pop();
  });
  where.pop();
  const photos = [];
  g.rows.forEach((row, r) =>
    row.forEach((image, c) => {
      const key = `${r}:${c}`;
      if (covered.has(key)) return;
      const t = anchors.get(key);
      photos.push(t ? { image: t.image, liked: true } : { image, liked: false });
    }),
  );
  return photos;
}
