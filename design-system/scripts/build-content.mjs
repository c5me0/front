function dartOf(v, className, n, classes = dartClasses) {
  const k = kindOf(v);
  if (k === 'string') return ['String', IMAGE_NAME.test(v) ? dImg(v) : dStr(v)];
  if (k === 'int') return ['int', String(v)];
  if (k === 'double') return ['double', dNum(v)];
  if (k === 'boolean') return ['bool', String(v)];
  if (k === 'array') {
    const itemClass = className;
    const items = v.map((x) => dartOf(x, itemClass, n + 1, classes));
    const type = items.some(([t]) => t === 'double') ? 'double' : items[0][0];
    return [`List<${type}>`, dList(items.map(([, e]) => e), n, type)];
  }
  const fields = Object.entries(v).map(([key, x]) => {
    const child = kindOf(x) === 'array' ? `${className}${pascalKey(singular(key))}` : `${className}${pascalKey(key)}`;
    const [type, expr] = dartOf(x, child, n + 1, classes);
    return { key, type, expr };
  });
  if (!classes.some((c) => c.name === className)) classes.push({ name: className, fields });
  return [className, `${className}(\n${fields.map((f) => `${ind(n + 1)}${f.key}: ${f.expr},`).join('\n')}\n${ind(n)})`];
}
