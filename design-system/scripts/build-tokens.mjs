function cssToHex(css) {
  const h2 = (n) => Math.round(n).toString(16).padStart(2, '0');
  const s = String(css).trim().toLowerCase();
  if (HEX.test(s)) return s.length === 9 && s.endsWith('ff') ? s.slice(0, 7) : s;
  const m = /^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)$/.exec(s);
  if (!m) return null;
  const [r, g, b] = [m[1], m[2], m[3]].map(Number);
  const a = m[4] === undefined ? 1 : Number(m[4]);
  if ([r, g, b].some((c) => c > 255) || a > 1) return null;

  const alpha = Math.round(a * 255 + 1e-6);
  return `#${h2(r)}${h2(g)}${h2(b)}${alpha === 255 ? '' : h2(alpha)}`;
}

