function systemTrackingAt(size) {
  const { points, upm } = systemTrackingTable;
  let units = points[points.length - 1][1];
  if (size <= points[0][0]) units = points[0][1];
  else {
    for (let i = 1; i < points.length; i++) {
      const [s1, u1] = points[i];
      if (size > s1) continue;
      const [s0, u0] = points[i - 1];
      units = u0 + ((u1 - u0) * (size - s0)) / (s1 - s0);
      break;
    }
  }
  return round((units * size) / upm);
}

