function strip(node) {
  if (Array.isArray(node)) return node.map(strip);
  if (!isObj(node)) return node;
  if ('$value' in node) return node.$value;
  const out = {};
  for (const [k, v] of Object.entries(node)) if (!k.startsWith('$')) out[k] = strip(v);
  return out;
}

function resolveRatios(node) {
  if (Array.isArray(node)) return node.map(resolveRatios);
  if (isObj(node)) return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, resolveRatios(v)]));
  if (typeof node === 'string' && RATIO.test(node)) {
    const [, a, b] = node.match(RATIO);
    return Number(a) / Number(b);
  }
  return node;
}

const camel = (parts) =>
  parts
    .flatMap((p) => String(p).split(/[^A-Za-z0-9]+/))
    .filter(Boolean)
    .map((p, i) => (i === 0 ? p.charAt(0).toLowerCase() + p.slice(1) : p.charAt(0).toUpperCase() + p.slice(1)))
    .join('');
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

function flatten(obj, prefix = [], out = []) {
  for (const [k, v] of Object.entries(obj)) {
    if (isObj(v)) flatten(v, [...prefix, k], out);
    else out.push([[...prefix, k], v]);
  }
  return out;
}

