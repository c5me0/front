let stale = false;
for (const [file, source] of [
  ...(process.argv.includes('--rn') ? [[OUT_TS, ts]] : []),
  [OUT_DART, dart],
]) {
  const content = generatedComments(source);
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (CHECK) {
    if (current !== content) {
      console.error(`✗ stale: ${file}`);
      stale = true;
    } else console.log(`✓ up to date: ${file}`);
    continue;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  console.log(`wrote ${file}`);
}
if (stale) {
  console.error('토큰 생성물이 tokens.json 과 다릅니다. `npm run tokens` 를 실행하세요.');
  process.exit(1);
}
